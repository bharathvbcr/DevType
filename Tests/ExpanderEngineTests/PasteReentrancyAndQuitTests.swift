import AppKit
import SourceTreeTestSupport
import XCTest
@testable import ExpanderEngine

// MARK: - The published payload: markers, quit, images, and what must not depend on us
//
// Second pass over how an expansion's payload reaches the pasteboard. The payload is concrete
// data in one marked item (see `PasteboardBroker.payloadItem`); a lazily provided payload was
// tried and removed. Facts the assertions rest on were measured against AppKit with a reader in
// a separate process on a named pasteboard (never the general one):
//
//  - a provider is fulfilled on the owner's main thread, and a reader waits for as long as that
//    thread is busy (1.5 s of blocked main = a 1.57 s read) — while this process's main thread
//    makes synchronous AX calls into the app that is reading;
//  - `exit`/`abort` with an unread promise leave the types advertised and no data behind them;
//    `NSApplication.terminate` provides the promise and leaves the payload on the board;
//  - while a publication runs, a reader sampling `types` sees the payload type before the
//    markers when the payload comes first (3,385 of 139,353 samples), and never when the markers
//    come first (0 of 167,009).
final class PasteReentrancyAndQuitTests: XCTestCase {
    typealias Harness = PasteResidencyTests.Harness

    private func pump(until deadline: TimeInterval) {
        while InputClock.monotonicNow() < deadline {
            RunLoop.main.run(until: Date().addingTimeInterval(0.01))
        }
    }

    @discardableResult
    private func pump(timeout: TimeInterval, until condition: () -> Bool) -> Bool {
        let deadline = InputClock.monotonicNow() + timeout
        while !condition(), InputClock.monotonicNow() < deadline {
            RunLoop.main.run(until: Date().addingTimeInterval(0.01))
        }
        return condition()
    }

    private func makeImage() -> NSImage {
        let rep = NSBitmapImageRep(
            bitmapDataPlanes: nil, pixelsWide: 4, pixelsHigh: 4, bitsPerSample: 8, samplesPerPixel: 4,
            hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0
        )!
        let image = NSImage(size: NSSize(width: 4, height: 4))
        image.addRepresentation(rep)
        return image
    }

    // MARK: - Markers go in before the payload

    func testTheMarkersPrecedeThePayloadInsideTheItem() throws {
        let item = try XCTUnwrap(PasteboardBroker.payloadItem(
            representations: [(.string, Data("SECRET".utf8))]
        ))

        XCTAssertEqual(
            item.types,
            [PasteboardBroker.transientType, PasteboardBroker.concealedType,
             PasteboardBroker.autoGeneratedType, .string],
            "types become visible to a reader in item order; a payload type ahead of the markers is a window in which a clipboard manager records it"
        )
    }

    func testAnImageItemCarriesItsMarkersFirstToo() throws {
        let broker = Harness().broker
        let prepared = broker.expansionImageRepresentations(image: makeImage(), imagePath: nil)
        let item = try XCTUnwrap(PasteboardBroker.payloadItem(representations: prepared.items))

        XCTAssertEqual(Array(item.types.prefix(3)), [
            PasteboardBroker.transientType, PasteboardBroker.concealedType, PasteboardBroker.autoGeneratedType
        ])
        XCTAssertTrue(item.types.contains(.png) || item.types.contains(.tiff))
    }

    /// One publication, one count move at the clear (an empty board), one item holding the payload
    /// and its markers — and the data is data, not a promise.
    func testThePayloadIsOneMarkedItemOfConcreteData() throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let broker = Harness().broker
        board.clearContents()
        board.setString("USER-OLD", forType: .string)
        let before = board.changeCount

        let ticket = try XCTUnwrap(broker.publishPayload(
            on: board, representations: [(.string, Data("SECRET".utf8))]
        ))

        XCTAssertEqual(ticket.targetChangeCount, before + 1, "one count move per publication, at the clear")
        XCTAssertEqual(board.changeCount, ticket.targetChangeCount, "writing the item must not move the count")
        XCTAssertEqual(board.pasteboardItems?.count, 1)
        let item = try XCTUnwrap(board.pasteboardItems?.first)
        XCTAssertTrue(Set(item.types).isSuperset(of: [
            .string, PasteboardBroker.transientType, PasteboardBroker.concealedType,
            PasteboardBroker.autoGeneratedType
        ]))
        XCTAssertEqual(item.string(forType: .string), "SECRET")
        XCTAssertEqual(board.clearContents(), ticket.targetChangeCount + 1)
        XCTAssertTrue((board.types ?? []).isEmpty, "at the instant the count moves the board holds nothing")
    }

    // MARK: - Quit with a payload on the board

    func testQuittingMidHoldPutsTheUsersClipboardBack() {
        let harness = Harness()
        harness.seedUserClipboard("USER-OLD")
        let postedAt = harness.paste("SNIPPET", in: self)
        let owned = harness.board.changeCount

        harness.broker.restorePendingClipboardForTermination()

        XCTAssertNotEqual(harness.board.changeCount, owned)
        XCTAssertEqual(harness.board.string(forType: .string), "USER-OLD",
                       "the release timers die with the process: the snippet would stay as the clipboard")
        let afterQuit = harness.board.changeCount
        pump(until: postedAt + 0.9)
        XCTAssertEqual(harness.board.changeCount, afterQuit, "no scheduled release acts on the restored board")
        XCTAssertEqual(harness.board.string(forType: .string), "USER-OLD")
    }

    /// No clipboard to give back: the payload must not survive the quit.
    func testQuittingWithNothingToRestoreLeavesAnEmptyBoard() {
        let harness = Harness()
        harness.paste("SNIPPET", in: self)

        harness.broker.restorePendingClipboardForTermination()

        XCTAssertTrue((harness.board.types ?? []).isEmpty, "the payload was left on the board")
    }

    func testQuittingNeverTouchesABoardSomeoneElseWrote() {
        let harness = Harness()
        harness.seedUserClipboard("USER-OLD")
        harness.paste("SNIPPET", in: self)
        harness.board.clearContents()
        harness.board.setString("USER-NEW", forType: .string)
        let before = harness.board.changeCount

        harness.broker.restorePendingClipboardForTermination()

        XCTAssertEqual(harness.board.changeCount, before)
        XCTAssertEqual(harness.board.string(forType: .string), "USER-NEW")
    }

    func testQuittingWithNothingPendingChangesNothing() {
        let harness = Harness()
        harness.seedUserClipboard("USER-OLD")
        let before = harness.board.changeCount

        harness.broker.restorePendingClipboardForTermination()

        XCTAssertEqual(harness.board.changeCount, before)
    }

    /// What the restore *does* is driven above (`testQuittingMidHoldPutsTheUsersClipboardBack` and its
    /// siblings, on a private board). That `applicationWillTerminate` calls it is the one thing
    /// those cannot reach: the call is on `PasteboardBroker.shared`, whose board is the user's real
    /// clipboard, and invoking the delegate's termination path headlessly would stop the live
    /// engine and write that board. So the call site is read from the source, on purpose — scoped
    /// to the termination function's own body.
    func testTheAppRestoresTheClipboardInItsTerminationPath() throws {
        let delegate = try SourceTree.text("Sources/DevTypeAppCore/AppDelegate.swift")
        let body = try SourceTree.functionBody("func applicationWillTerminate(", in: delegate)
        XCTAssertTrue(
            body.contains("PasteboardBroker.shared.restorePendingClipboardForTermination()"),
            "quitting inside a paste hold leaves the snippet as the user's clipboard"
        )
    }

    // MARK: - Image snippets

    /// An image is published like a text payload: the user's clipboard back after the residency.
    func testAnImagePayloadIsOnTheBoardThroughItsResidencyAndReleasedAfter() {
        let harness = Harness()
        harness.seedUserClipboard("USER-OLD")
        harness.pasteImage(makeImage(), in: self)
        let postedAt = InputClock.monotonicNow()

        pump(until: postedAt + 0.30)
        XCTAssertNotNil(harness.hostRead(in: self) { $0.data(forType: .png) }, "the image is readable inside its residency")

        pump(until: postedAt + 1.30)
        XCTAssertEqual(harness.board.string(forType: .string), "USER-OLD")
        XCTAssertNil(harness.board.data(forType: .png))
    }

    /// An image published over a text payload still inside its lease makes that host paste the image.
    func testAnImagePasteWaitsForATextPayloadInsideItsLease() {
        let harness = Harness()
        harness.seedUserClipboard("USER-OLD")
        let firstPostedAt = harness.paste("FIRST", in: self)

        pump(until: firstPostedAt + 0.10)
        harness.pasteImage(makeImage(), in: self, waitForChord: false)
        pump(until: firstPostedAt + 0.30)

        XCTAssertEqual(harness.hostRead(in: self), "FIRST",
                       "the image replaced a text payload still inside its lease")
        XCTAssertTrue(pump(timeout: 3) { harness.posted.events >= 8 }, "the image still pastes afterwards")
        XCTAssertNotNil(harness.hostRead(in: self) { $0.data(forType: .png) })
    }

    /// The user's ⌘C lands between the snapshot of their clipboard and the image's publication. The
    /// image path used to clear the board without checking: the new copy was erased, and the older
    /// snapshot restored over it later.
    func testACopyThatLandsBetweenTheSnapshotAndAnImagePublicationSurvives() {
        var injected = false
        var harness: Harness!
        harness = Harness(snapshot: { board in
            if !injected {
                injected = true
                let stale = PasteboardBroker.snapshotPasteboard(board)
                board.clearContents()
                board.setString("USER-NEW", forType: .string)
                return stale
            }
            return PasteboardBroker.snapshotPasteboard(board)
        })
        harness.seedUserClipboard("USER-OLD")
        harness.pasteImage(makeImage(), in: self)
        let postedAt = InputClock.monotonicNow()

        pump(until: postedAt + 1.30)

        XCTAssertEqual(harness.board.string(forType: .string), "USER-NEW",
                       "the user's new copy was replaced by the older clipboard we had snapshotted")
    }

    // MARK: - Secrets

    /// Nothing of the payload remains once the board is restored: no promise, no provider holding the
    /// string. (With nothing to give back the board is simply empty.)
    func testARestoredBoardHoldsNothingOfThePayload() throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let broker = Harness().broker
        let ticket = try XCTUnwrap(broker.publishPayload(
            on: board, representations: [(.string, Data("hunter2-SECRET".utf8))]
        ))

        broker.restore(ticket)

        XCTAssertTrue((board.types ?? []).isEmpty)
        XCTAssertNil(board.string(forType: .string))
    }
}

extension PasteResidencyTests.Harness {
    /// Publishes `image` and posts ⌘V. With `waitForChord` the call returns once the chord is out.
    func pasteImage(_ image: NSImage, in test: XCTestCase, waitForChord: Bool = true) {
        broker.pasteImageViaClipboard(image: image, imagePath: nil, bundleID: nil, focus: .resolved(nil)) { _ in }
        guard waitForChord else { return }
        let target = posted.events + 4
        let deadline = InputClock.monotonicNow() + 3
        while posted.events < target, InputClock.monotonicNow() < deadline {
            RunLoop.main.run(until: Date().addingTimeInterval(0.01))
        }
    }
}
