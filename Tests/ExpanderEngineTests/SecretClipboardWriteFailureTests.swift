    private func verifyDeadline(_ duration: TimeInterval, expected: TimeInterval) {
        let clipboard = SecretClipboard()
        let writer = Writer(failure: .none)
        var scheduled: [() -> Void] = []
        let result = clipboard.copyResult(
            "synthetic secret", clearAfter: duration, pasteboardWriter: writer, broker: nil,
            schedule: { action, delay in
                XCTAssertEqual(delay, expected)
                scheduled.append(action)
            }
        )
        guard case .copied(let date) = result else { return XCTFail("Copy failed") }
        XCTAssertTrue(date.timeIntervalSinceNow.isFinite)
        XCTAssertEqual(scheduled.count, 1)
        scheduled.first?()
        XCTAssertNil(writer.currentString)
    }
    private final class Writer: SecretPasteboardWriting {
        enum Failure { case none, string, concealed, transient, generated }

        let failure: Failure
        private(set) var clearCount = 0
        private(set) var stringWrites = 0
        private(set) var dataWrites: [NSPasteboard.PasteboardType] = []
        private(set) var changeCount = 0
        private(set) var currentString: String?
        var externalCopyDuringGeneratedMarker: String?
        var externalCopyAfterString: String?
        /// Fail only the first N string writes. Later writes (the parked restore) succeed.
        var failStringWrites = 0

        init(failure: Failure) { self.failure = failure }

        @discardableResult
        func clearContents() -> Int {
            clearCount += 1
            changeCount += 1
            currentString = nil
            let owned = changeCount
            if takeoverAfterNextClear {
                takeoverAfterNextClear = false
                changeCount += 1
                currentString = nil
            }
            return owned
        }

        func setString(_ string: String, forType dataType: NSPasteboard.PasteboardType) -> Bool {
            stringWrites += 1
            if failStringWrites > 0 {
                failStringWrites -= 1
                return false
            }
            guard failure != .string else { return false }
            currentString = string
            if let externalCopyAfterString { simulateExternalCopy(externalCopyAfterString) }
            switch takeoverAfterNextString {
            case .none:
                break
            case .emptyBoard:
                takeoverAfterNextString = .none
                changeCount += 1
                currentString = nil
            case .replaced(let text):
                takeoverAfterNextString = .none
                changeCount += 1
                currentString = text
            }
            return true
        }

        func setData(_ data: Data?, forType dataType: NSPasteboard.PasteboardType) -> Bool {
            dataWrites.append(dataType)
            let shouldFail = (failure == .concealed && dataType == PasteboardBroker.concealedType)
                || (failure == .transient && dataType == PasteboardBroker.transientType)
                || (failure == .generated && dataType == PasteboardBroker.autoGeneratedType)
            guard !shouldFail else { return false }
            if dataType == PasteboardBroker.autoGeneratedType,
               let externalCopyDuringGeneratedMarker {
                simulateExternalCopy(externalCopyDuringGeneratedMarker)
            }
            return true
        }

        func simulateExternalCopy(_ string: String) {
            changeCount += 1
            currentString = string
        }

        /// Another owner touched the board. Content is left exactly as it is now.
        func noteExternalOwner() {
            changeCount += 1
        }

        /// Next `clearContents` returns its count, then the count moves and the board stays empty.
        var takeoverAfterNextClear = false
        /// Next successful string write is recorded, then the count moves and the string is replaced.
        var takeoverAfterNextString: PostWriteTakeover = .none

        enum PostWriteTakeover {
            case none
            case emptyBoard
            case replaced(String)
        }

        func string(forType type: NSPasteboard.PasteboardType) -> String? {
            type == .string ? currentString : nil
        }
    }

