import AppKit
import XCTest
@testable import ExpanderEngine

final class SecretClipboardWriteFailureTests: XCTestCase {

    func testNegativeClearDeadlineUsesTheDefault() {
        verifyDeadline(-1, expected: SecretClipboard.defaultClearAfter)
    }

    func testNonFiniteAndExtremeClearDeadlinesStayBounded() {
        for invalid in [Double.nan, .infinity, -.infinity] {
            verifyDeadline(invalid, expected: SecretClipboard.defaultClearAfter)
        }
        verifyDeadline(.greatestFiniteMagnitude, expected: 86_400)
        verifyDeadline(0, expected: 0)
    }

    private func verifyDeadline(_ duration: TimeInterval, expected: TimeInterval) {
        let clipboard = SecretClipboard()
        let writer = Writer(failure: .none)
        var scheduled: [() -> Void] = []
        let result = clipboard.copyResult(
            "synthetic secret", clearAfter: duration, pasteboardWriter: writer, broker: nil,
            schedule: { action, delay in
                XCTAssertEqual(delay, expected)
                scheduled.append(action)
            }
        )
        guard case .copied(let date) = result else { return XCTFail("Copy failed") }
        XCTAssertTrue(date.timeIntervalSinceNow.isFinite)
        XCTAssertEqual(scheduled.count, 1)
        scheduled.first?()
        XCTAssertNil(writer.currentString)
    }
    private final class Writer: SecretPasteboardWriting {
        enum Failure { case none, string, concealed, transient, generated }

        let failure: Failure
        private(set) var clearCount = 0
        private(set) var stringWrites = 0
        private(set) var dataWrites: [NSPasteboard.PasteboardType] = []
        private(set) var changeCount = 0
        private(set) var currentString: String?
        var externalCopyDuringGeneratedMarker: String?
        var externalCopyAfterString: String?

        init(failure: Failure) { self.failure = failure }

        @discardableResult
        func clearContents() -> Int {
            clearCount += 1
            changeCount += 1
            currentString = nil
            return changeCount
        }

        func setString(_ string: String, forType dataType: NSPasteboard.PasteboardType) -> Bool {
            stringWrites += 1
            guard failure != .string else { return false }
            currentString = string
            if let externalCopyAfterString { simulateExternalCopy(externalCopyAfterString) }
            return true
        }

        func setData(_ data: Data?, forType dataType: NSPasteboard.PasteboardType) -> Bool {
            dataWrites.append(dataType)
            let shouldFail = (failure == .concealed && dataType == PasteboardBroker.concealedType)
                || (failure == .transient && dataType == PasteboardBroker.transientType)
                || (failure == .generated && dataType == PasteboardBroker.autoGeneratedType)
            guard !shouldFail else { return false }
            if dataType == PasteboardBroker.autoGeneratedType,
               let externalCopyDuringGeneratedMarker {
                simulateExternalCopy(externalCopyDuringGeneratedMarker)
            }
            return true
        }

        func simulateExternalCopy(_ string: String) {
            changeCount += 1
            currentString = string
        }
    }

    func testStringWriteFailureReturnsTypedFailureAndSchedulesNothing() {
        let clipboard = SecretClipboard()
        let writer = Writer(failure: .string)
        var scheduled = 0

        let result = clipboard.copyResult(
            "secret",
            pasteboardWriter: writer,
            schedule: { _, _ in scheduled += 1 }
        )

        XCTAssertEqual(result, .writeFailed)
        XCTAssertEqual(scheduled, 0)
        XCTAssertFalse(clipboard.hasOutstandingSecret)
    }

    func testAnyMissingConcealmentMarkerFailsClosedAndRemovesOurPayload() {
        for failure in [Writer.Failure.concealed, .transient, .generated] {
            let clipboard = SecretClipboard()
            let writer = Writer(failure: failure)
            var scheduled = 0

            let result = clipboard.copyResult(
                "secret",
                pasteboardWriter: writer,
                schedule: { _, _ in scheduled += 1 }
            )

            XCTAssertEqual(result, .writeFailed)
            XCTAssertEqual(writer.clearCount, 2, "The initial clear and failure cleanup must both run")
            XCTAssertEqual(scheduled, 0)
            XCTAssertFalse(clipboard.hasOutstandingSecret)
        }
    }

    func testSuccessfulWriteReportsDeadlineAndSchedulesExactlyOnce() {
        let clipboard = SecretClipboard()
        let writer = Writer(failure: .none)
        var scheduled = 0

        let result = clipboard.copyResult(
            "secret",
            clearAfter: 20,
            pasteboardWriter: writer,
            schedule: { _, delay in
                scheduled += 1
                XCTAssertEqual(delay, 20)
            }
        )

        guard case .copied(let clearAt) = result else {
            return XCTFail("expected copied, got \(result)")
        }
        XCTAssertGreaterThan(clearAt, Date())
        XCTAssertEqual(scheduled, 1)
        XCTAssertTrue(clipboard.hasOutstandingSecret)
    }

    func testSupersededScheduledClearCannotEraseNewerOwnership() {
        let clipboard = SecretClipboard()
        let writer = Writer(failure: .none)
        var scheduled: [() -> Void] = []

        XCTAssertTrue(clipboard.copyResult(
            "first secret",
            pasteboardWriter: writer,
            schedule: { action, _ in scheduled.append(action) }
        ).didCopy)
        XCTAssertTrue(clipboard.copyResult(
            "newer secret",
            pasteboardWriter: writer,
            schedule: { action, _ in scheduled.append(action) }
        ).didCopy)
        XCTAssertEqual(scheduled.count, 2)

        scheduled[0]()
        XCTAssertTrue(
            clipboard.hasOutstandingSecret,
            "An old timer must not clear the ownership ticket installed by a newer copy."
        )
        XCTAssertEqual(
            writer.clearCount,
            2,
            "The stale timer must not touch the newer pasteboard payload."
        )
        XCTAssertEqual(writer.currentString, "newer secret")

        scheduled[1]()
        XCTAssertFalse(clipboard.hasOutstandingSecret)
        XCTAssertEqual(writer.clearCount, 3)
        XCTAssertNil(writer.currentString)
    }

    func testExternalOwnershipTakenDuringWriteIsNeverAdoptedOrCleared() {
        let clipboard = SecretClipboard()
        let writer = Writer(failure: .none)
        writer.externalCopyDuringGeneratedMarker = "external owner"
        var scheduled = 0

        XCTAssertEqual(
            clipboard.copyResult(
                "secret",
                pasteboardWriter: writer,
                schedule: { _, _ in scheduled += 1 }
            ),
            .writeFailed
        )
        XCTAssertEqual(scheduled, 0)
        XCTAssertFalse(clipboard.hasOutstandingSecret)
        XCTAssertEqual(writer.clearCount, 1)
        XCTAssertEqual(writer.currentString, "external owner")
    }

    func testEmptyInputIsDistinctAndLeavesWriterUntouched() {
        let clipboard = SecretClipboard()
        let writer = Writer(failure: .none)

        XCTAssertEqual(clipboard.copyResult("", pasteboardWriter: writer), .empty)
        XCTAssertEqual(writer.clearCount, 0)
        XCTAssertFalse(clipboard.hasOutstandingSecret)
    }

    func testExternalOwnerBeforeFailedMarkerIsNotClearedOrScheduled() {
        for failure in [Writer.Failure.concealed, .transient, .generated] {
            let clipboard = SecretClipboard()
            let writer = Writer(failure: failure)
            writer.externalCopyAfterString = "external copy"
            var scheduled = 0
            let result = clipboard.copyResult(
                "synthetic secret", pasteboardWriter: writer, broker: nil,
                schedule: { _, _ in scheduled += 1 }
            )
            XCTAssertEqual(result, .writeFailed)
            XCTAssertEqual(writer.clearCount, 1, "Cleanup authority belongs to the original clear count.")
            XCTAssertEqual(writer.currentString, "external copy")
            XCTAssertEqual(scheduled, 0)
            XCTAssertFalse(clipboard.hasOutstandingSecret)
        }
    }

    func testParkedClipboardReturnsWhenSecretWriteFails() {
        let parked = "parked-user-clipboard"
        let (broker, board) = park(parked)
        defer { board.releaseGlobally() }
        let clipboard = SecretClipboard()
        let writer = Writer(failure: .concealed)

        let result = clipboard.copyResult(
            "secret",
            pasteboardWriter: writer,
            broker: broker,
            schedule: { _, _ in XCTFail("A failed secret write must not schedule a clear") }
        )

        XCTAssertEqual(result, .writeFailed)
        XCTAssertFalse(result.didCopy)
        XCTAssertEqual(
            writer.currentString, parked,
            "A failed secret copy must put the expansion's parked user clipboard back"
        )
        XCTAssertFalse(writer.currentString?.isEmpty ?? true)
    }

    func testParkedClipboardReturnsWhenSecretTimerClears() {
        let parked = "parked-user-clipboard"
        let (broker, board) = park(parked)
        defer { board.releaseGlobally() }
        let clipboard = SecretClipboard()
        let writer = Writer(failure: .none)
        var fire: (() -> Void)?

        let result = clipboard.copyResult(
            "secret",
            pasteboardWriter: writer,
            broker: broker,
            schedule: { action, _ in fire = action }
        )

        XCTAssertTrue(result.didCopy)
        XCTAssertEqual(writer.currentString, "secret")
        fire?()
        XCTAssertEqual(
            writer.currentString, parked,
            "The timed clear must restore the parked user clipboard, not leave the board empty"
        )
        XCTAssertFalse(clipboard.hasOutstandingSecret)
    }

    func testUnicodeParkedClipboardRoundTripsOnFailureAndOnTheTimer() {
        let parked = "café 🔐 東京 — “quotes”"
        let (failBroker, failBoard) = park(parked)
        defer { failBoard.releaseGlobally() }
        let failWriter = Writer(failure: .transient)
        XCTAssertEqual(
            SecretClipboard().copyResult(
                "secret",
                pasteboardWriter: failWriter,
                broker: failBroker,
                schedule: { _, _ in }
            ),
            .writeFailed
        )
        XCTAssertEqual(failWriter.currentString, parked)

        let (broker, board) = park(parked)
        defer { board.releaseGlobally() }
        var fire: (() -> Void)?
        let clipboard = SecretClipboard()
        XCTAssertTrue(clipboard.copyResult(
            "secret",
            pasteboard: board,
            broker: broker,
            schedule: { action, _ in fire = action }
        ).didCopy)
        XCTAssertEqual(board.string(forType: .string), "secret")
        fire?()
        XCTAssertEqual(board.string(forType: .string), parked)
        XCTAssertEqual(board.data(forType: .string), Data(parked.utf8))
    }

    func testNoPendingTicketStillClearsOnTheTimerAndFailureIsNotSuccess() {
        let broker = PasteboardBroker()
        let clipboard = SecretClipboard()
        let success = Writer(failure: .none)
        var fire: (() -> Void)?
        XCTAssertTrue(clipboard.copyResult(
            "secret",
            pasteboardWriter: success,
            broker: broker,
            schedule: { action, _ in fire = action }
        ).didCopy)
        fire?()
        XCTAssertNil(success.currentString)
        XCTAssertFalse(clipboard.hasOutstandingSecret)

        let failure = Writer(failure: .string)
        let failed = clipboard.copyResult(
            "secret",
            pasteboardWriter: failure,
            broker: PasteboardBroker(),
            schedule: { _, _ in XCTFail("Failure must not schedule") }
        )
        XCTAssertEqual(failed, .writeFailed)
        XCTAssertFalse(failed.didCopy)
        XCTAssertNil(failure.currentString)
    }

    func testUserChangeBeforeTimerDoesNotWriteParkedItems() {
        let parked = "parked-user-clipboard"
        let (broker, board) = park(parked)
        defer { board.releaseGlobally() }
        let clipboard = SecretClipboard()
        let writer = Writer(failure: .none)
        var fire: (() -> Void)?
        XCTAssertTrue(clipboard.copyResult(
            "secret",
            pasteboardWriter: writer,
            broker: broker,
            schedule: { action, _ in fire = action }
        ).didCopy)
        let writesBeforeTimer = writer.stringWrites
        writer.simulateExternalCopy("the user copy")

        fire?()

        XCTAssertEqual(writer.currentString, "the user copy")
        XCTAssertEqual(
            writer.stringWrites, writesBeforeTimer,
            "A moved change count is supersededByUser; the parked snapshot must not be written"
        )
        XCTAssertFalse(clipboard.hasOutstandingSecret)
    }

    func testConcealedParkedSnapshotIsNotRestoredAsTheUserClipboard() {
        XCTAssertFalse(
            PasteboardBroker.mayAdoptAsUserClipboard(types: [.string, PasteboardBroker.concealedType])
        )
        let (failBroker, failBoard) = park(
            "do-not-restore-secret",
            extra: [PasteboardBroker.concealedType: Data()]
        )
        defer { failBoard.releaseGlobally() }
        let failWriter = Writer(failure: .generated)
        XCTAssertEqual(
            SecretClipboard().copyResult(
                "secret",
                pasteboardWriter: failWriter,
                broker: failBroker,
                schedule: { _, _ in }
            ),
            .writeFailed
        )
        XCTAssertNotEqual(failWriter.currentString, "do-not-restore-secret")
        XCTAssertNil(failWriter.currentString)

        let (broker, board) = park(
            "do-not-restore-secret",
            extra: [PasteboardBroker.concealedType: Data()]
        )
        defer { board.releaseGlobally() }
        let clipboard = SecretClipboard()
        let writer = Writer(failure: .none)
        var fire: (() -> Void)?
        XCTAssertTrue(clipboard.copyResult(
            "secret",
            pasteboardWriter: writer,
            broker: broker,
            schedule: { action, _ in fire = action }
        ).didCopy)
        fire?()
        XCTAssertNil(writer.currentString)
        XCTAssertNotEqual(writer.currentString, "do-not-restore-secret")
    }

    func testEmptySecretDoesNotDropAPendingRestoreTicket() {
        let parked = "still-parked"
        let (broker, board) = park(parked)
        defer { board.releaseGlobally() }
        let clipboard = SecretClipboard()
        let writer = Writer(failure: .none)
        let generation = broker.currentRestoreGeneration()

        XCTAssertEqual(
            clipboard.copyResult("", pasteboardWriter: writer, broker: broker),
            .empty
        )
        XCTAssertEqual(broker.currentRestoreGeneration(), generation)
        XCTAssertEqual(writer.clearCount, 0)

        var fire: (() -> Void)?
        XCTAssertTrue(clipboard.copyResult(
            "secret",
            pasteboardWriter: writer,
            broker: broker,
            schedule: { action, _ in fire = action }
        ).didCopy)
        fire?()
        XCTAssertEqual(writer.currentString, parked)
    }

    func testOverlappingSecretCopiesDoNotRestoreTheFirstSecret() {
        let parked = "parked-user-clipboard"
        let (broker, board) = park(parked)
        defer { board.releaseGlobally() }
        let clipboard = SecretClipboard()
        let writer = Writer(failure: .none)
        var scheduled: [() -> Void] = []

        XCTAssertTrue(clipboard.copyResult(
            "secret-one",
            pasteboardWriter: writer,
            broker: broker,
            schedule: { action, _ in scheduled.append(action) }
        ).didCopy)
        XCTAssertTrue(clipboard.copyResult(
            "secret-two",
            pasteboardWriter: writer,
            broker: broker,
            schedule: { action, _ in scheduled.append(action) }
        ).didCopy)
        XCTAssertEqual(scheduled.count, 2)

        scheduled[0]()
        XCTAssertEqual(writer.currentString, "secret-two")
        XCTAssertNotEqual(writer.currentString, "secret-one")
        XCTAssertTrue(clipboard.hasOutstandingSecret)

        scheduled[1]()
        XCTAssertNotEqual(writer.currentString, "secret-one")
        XCTAssertNotEqual(writer.currentString, "secret-two")
        XCTAssertEqual(
            writer.currentString, parked,
            "The second clear restores the parked user clipboard, never the earlier secret"
        )
        XCTAssertFalse(clipboard.hasOutstandingSecret)
    }

    private func park(
        _ text: String,
        extra: [NSPasteboard.PasteboardType: Data] = [:]
    ) -> (PasteboardBroker, NSPasteboard) {
        let broker = PasteboardBroker()
        let board = NSPasteboard(name: NSPasteboard.Name("devtype.tests.secret.park.\(UUID())"))
        var item: [NSPasteboard.PasteboardType: Data] = [.string: Data(text.utf8)]
        for (type, data) in extra {
            item[type] = data
        }
        let generation = broker.beginRestoreGeneration()
        broker.registerPendingTicket(PasteboardBroker.ClipboardTicket(
            pasteboard: board,
            oldItems: [item],
            generation: generation,
            targetChangeCount: board.changeCount
        ))
        return (broker, board)
    }

}
