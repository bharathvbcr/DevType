import AppKit
import SourceTreeTestSupport
import XCTest
@testable import ExpanderEngine

/// A clipboard manager notices a pasteboard change and reads the board — usually within a
/// millisecond or two of `clearContents()`, because that is when the change count moves. The
/// nspasteboard.org markers are what tell it to skip the entry, so the board must never hold the
/// payload without them. Writing the payload first and the markers after leaves a window, one
/// pasteboard round trip per marker wide, in which a secret is readable and unmarked.
///
/// The text paste publishes payload and markers as a single item (`PasteResidencyWitnessTests`).
/// The secret copy and the image paste write representation by representation, so their order is
/// the guarantee: markers first.
final class ConcealedPublicationOrderTests: XCTestCase {
    /// Records the pasteboard state after every write, and whether it was ever exposed.
    private final class RecordingWriter: SecretPasteboardWriting {
        private(set) var changeCount = 0
        private var types: Set<String> = []
        private(set) var exposedWithoutMarkers = false
        private(set) var order: [String] = []

        @discardableResult func clearContents() -> Int {
            changeCount += 1
            types = []
            order.append("clear")
            return changeCount
        }

        func setString(_ string: String, forType dataType: NSPasteboard.PasteboardType) -> Bool {
            record(dataType)
        }

        func setData(_ data: Data?, forType dataType: NSPasteboard.PasteboardType) -> Bool {
            record(dataType)
        }

        private func record(_ type: NSPasteboard.PasteboardType) -> Bool {
            types.insert(type.rawValue)
            order.append(type.rawValue)
            let hasPayload = types.contains(NSPasteboard.PasteboardType.string.rawValue)
            let hasMarkers = [PasteboardBroker.concealedType, PasteboardBroker.transientType]
                .allSatisfy { types.contains($0.rawValue) }
            if hasPayload && !hasMarkers { exposedWithoutMarkers = true }
            return true
        }
    }

    func testASecretIsNeverOnTheBoardWithoutItsMarkers() {
        let writer = RecordingWriter()
        let outcome = SecretClipboard().copyResult(
            "correct horse battery staple", pasteboardWriter: writer, broker: nil,
            schedule: { _, _ in }
        )

        XCTAssertTrue(outcome.didCopy)
        XCTAssertFalse(
            writer.exposedWithoutMarkers,
            "the secret was readable before it was marked concealed/transient — order: \(writer.order)"
        )
        XCTAssertEqual(writer.order.first, "clear")
    }

    /// The helper that orders every marked, representation-by-representation publication.
    func testMarkersAreWrittenBeforeAnyPayloadRepresentation() {
        let writer = RecordingWriter()
        let writes = PasteboardBroker.concealedPublication(
            on: writer,
            payload: [{ writer.setData(Data("png".utf8), forType: .png) },
                      { writer.setData(Data("tiff".utf8), forType: .tiff) }]
        )
        writer.clearContents()
        XCTAssertTrue(writes.allSatisfy { $0() })

        XCTAssertEqual(Set(writer.order[1...3]), [PasteboardBroker.transientType.rawValue,
                                                  PasteboardBroker.concealedType.rawValue,
                                                  PasteboardBroker.autoGeneratedType.rawValue])
        XCTAssertEqual(Array(writer.order.suffix(2)), [NSPasteboard.PasteboardType.png.rawValue,
                                                       NSPasteboard.PasteboardType.tiff.rawValue])
    }

    /// The image paste writes through `NSPasteboard.general` (it has no injectable board), so its
    /// order is pinned at the source: the markers go in at index 0, never appended after the bytes.
    func testImagePasteInsertsItsMarkersAheadOfTheImageBytes() throws {
        let source = SourceContractTests.strippingComments(
            try SourceTree.text("Sources/ExpanderEngine/Engine/PasteboardBroker.swift")
        )
        let start = try XCTUnwrap(source.range(of: "public func pasteImageViaClipboard("))
        let end = try XCTUnwrap(source.range(of: "private func runImageHoldLoop("))
        let body = String(source[start.lowerBound..<end.lowerBound])
        XCTAssertTrue(body.contains("at: 0)"), "the image paste must put its markers ahead of the image bytes")
        XCTAssertFalse(body.contains("representations.append(contentsOf: ["),
                       "markers appended after the bytes leave the image readable and unmarked")
    }
}
