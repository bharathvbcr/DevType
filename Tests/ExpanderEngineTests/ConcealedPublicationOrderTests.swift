import AppKit
import XCTest
@testable import ExpanderEngine

/// A clipboard manager notices a pasteboard change and reads the board — usually within a
/// millisecond or two of `clearContents()`, because that is when the change count moves. The
/// nspasteboard.org markers are what tell it to skip the entry, so the board must never hold the
/// payload without them. Writing the payload first and the markers after leaves a window, one
/// pasteboard round trip per marker wide, in which a secret is readable and unmarked.
///
/// The text and image pastes publish payload and markers as a single item (`PasteReentrancyAndQuitTests`).
/// The secret copy writes representation by representation, so its order is
/// the guarantee: markers first.
final class ConcealedPublicationOrderTests: XCTestCase {
    /// Records the pasteboard state after every write, and whether it was ever exposed.
    private final class RecordingWriter: SecretPasteboardWriting {
        private(set) var changeCount = 0
        private var types: Set<String> = []
        private(set) var exposedWithoutMarkers = false
        private(set) var order: [String] = []

        @discardableResult func clearContents() -> Int {
            changeCount += 1
            types = []
            order.append("clear")
            return changeCount
        }

        func setString(_ string: String, forType dataType: NSPasteboard.PasteboardType) -> Bool {
            record(dataType)
        }

        func setData(_ data: Data?, forType dataType: NSPasteboard.PasteboardType) -> Bool {
            record(dataType)
        }

        private func record(_ type: NSPasteboard.PasteboardType) -> Bool {
            types.insert(type.rawValue)
            order.append(type.rawValue)
            let hasPayload = types.contains(NSPasteboard.PasteboardType.string.rawValue)
            let hasMarkers = [PasteboardBroker.concealedType, PasteboardBroker.transientType]
                .allSatisfy { types.contains($0.rawValue) }
            if hasPayload && !hasMarkers { exposedWithoutMarkers = true }
            return true
        }
    }

    func testASecretIsNeverOnTheBoardWithoutItsMarkers() {
        let writer = RecordingWriter()
        let outcome = SecretClipboard().copyResult(
            "correct horse battery staple", pasteboardWriter: writer, broker: nil,
            schedule: { _, _ in }
        )

        XCTAssertTrue(outcome.didCopy)
        XCTAssertFalse(
            writer.exposedWithoutMarkers,
            "the secret was readable before it was marked concealed/transient — order: \(writer.order)"
        )
        XCTAssertEqual(writer.order.first, "clear")
    }

    /// The helper that orders every marked, representation-by-representation publication.
    func testMarkersAreWrittenBeforeAnyPayloadRepresentation() {
        let writer = RecordingWriter()
        let writes = PasteboardBroker.concealedPublication(
            on: writer,
            payload: [{ writer.setData(Data("png".utf8), forType: .png) },
                      { writer.setData(Data("tiff".utf8), forType: .tiff) }]
        )
        writer.clearContents()
        XCTAssertTrue(writes.allSatisfy { $0() })

        XCTAssertEqual(Set(writer.order[1...3]), [PasteboardBroker.transientType.rawValue,
                                                  PasteboardBroker.concealedType.rawValue,
                                                  PasteboardBroker.autoGeneratedType.rawValue])
        XCTAssertEqual(Array(writer.order.suffix(2)), [NSPasteboard.PasteboardType.png.rawValue,
                                                       NSPasteboard.PasteboardType.tiff.rawValue])
    }

    /// The image paste leaves the board as one item whose markers come ahead of the image bytes,
    /// reached by one count move at the clear — what a clipboard manager that notices the change
    /// reads. A write list of its own, one representation after another, would leave the bytes
    /// readable ahead of (or without) the markers; that shows up here as the markers trailing the
    /// image in `types`. Run through the real `pasteImageViaClipboard` on a private board, with ⌘V
    /// recorded and never posted.
    func testAnImagePasteLeavesOneMarkedItemWithTheMarkersAheadOfTheImageBytes() throws {
        let harness = try InjectionHarness()
        harness.seedUserClipboard("USER")
        harness.hostPastes = false
        let before = harness.board.changeCount
        let rep = try XCTUnwrap(NSBitmapImageRep(
            bitmapDataPlanes: nil, pixelsWide: 4, pixelsHigh: 4, bitsPerSample: 8, samplesPerPixel: 4,
            hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0
        ))
        let image = NSImage(size: NSSize(width: 4, height: 4))
        image.addRepresentation(rep)

        var result: PasteboardBroker.PasteDeliveryResult?
        harness.broker.pasteImageViaClipboard(image: image, imagePath: nil, bundleID: nil, focus: .resolved(harness.field)) {
            result = $0
        }
        // The payload is on the board from publication until the paste's residency ends.
        harness.pump(in: self, timeout: 5, "the image to be published") {
            harness.board.data(forType: .png) != nil || harness.board.data(forType: .tiff) != nil
        }
        let items = try XCTUnwrap(harness.board.pasteboardItems)
        XCTAssertEqual(items.count, 1, "one item, not one per representation")
        let types = items[0].types
        let markers: [NSPasteboard.PasteboardType] = [
            PasteboardBroker.transientType, PasteboardBroker.concealedType, PasteboardBroker.autoGeneratedType
        ]
        XCTAssertEqual(Set(types.prefix(3)), Set(markers), "the markers lead the item: \(types.map(\.rawValue))")
        let firstImage = try XCTUnwrap(types.firstIndex { $0 == .png || $0 == .tiff }, "\(types.map(\.rawValue))")
        for marker in markers {
            XCTAssertLessThan(try XCTUnwrap(types.firstIndex(of: marker)), firstImage)
        }
        XCTAssertEqual(harness.board.changeCount, before + 1, "one count move for the whole publication")

        harness.pump(in: self, timeout: 5, "the paste to answer") { result != nil }
        XCTAssertEqual(harness.chords, 1)
    }
}
