    public func attemptAXDirectInjection(text: String) -> Bool {
        guard let axElement = AXContextChecker.shared.focusedElement() else { return false }
        // Baseline before the write so `verifyTextDelivery` can distinguish "nothing happened" from
        // "it happened but the host reports a stale value". Without it a real insert can be judged
        // failed, and the caller then pastes the same text a second time.
        let baseline = focusedTextObservation(for: axElement)
        let result = AXUIElementSetAttributeValue(axElement, kAXSelectedTextAttribute as CFString, text as CFTypeRef)
        guard result == .success else { return false }
        switch Self.verifyTextDelivery(
            expectedText: text,
            baseline: baseline,
            after: focusedTextObservation(for: axElement)
        ) {
        case .failed:
            return false
        case .delivered, .unavailable:
            return true
        }
    }

    public func pasteViaClipboard(text: String, completion: ((Bool) -> Void)? = nil) {
        pasteViaClipboard(text: text, expectedText: nil, baseline: nil) { result in
            completion?(result != .notPosted)
        }
    }

    /// Clipboard paste that holds our payload until AX confirms delivery, a confirmed miss exhausts
    /// retries, or the hold timeout expires (unverified). Restores the prior pasteboard afterward.
    ///
    /// - Parameters:
    ///   - leaveClipboardOnFailure: When true, skip immediate restore on `.notPosted` / `.failed` so the
    ///     concealed payload remains for a manual ⌘V (secure clipboard paste under Secure Input).
    ///   - holdTimeoutOverride: Optional longer hold (e.g. secure clipboard paste under SI).
    ///   - completeBeforeRestore: When true and no `expectedText`, report `.unavailable` right after
    ///     Cmd+V so callers are not blocked for the full hold window.
    public func pasteViaClipboard(
        text: String,
        expectedText: String?,
        baseline: FocusedTextObservation?,
        leaveClipboardOnFailure: Bool = false,
        holdTimeoutOverride: TimeInterval? = nil,
        completeBeforeRestore: Bool = false,
        completion: @escaping (PasteDeliveryResult) -> Void
    ) {
        // Re-check Post Events at paste time.
        guard CGPreflightPostEventAccess() else {
            DevTypeLog.inject.error("[Inject] paste refused — Post Events denied at paste time")
            completion(.notPosted)
            return
        }

        let pasteboard = NSPasteboard.general

        let oldItems = pasteboard.pasteboardItems?.compactMap { item -> [NSPasteboard.PasteboardType: Data]? in
            var dict = [NSPasteboard.PasteboardType: Data]()
            for type in item.types {
                if let data = item.data(forType: type) {
                    dict[type] = data
                }
            }
            return dict
        }

        let generation = beginRestoreGeneration()

        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        pasteboard.setData(Data(), forType: transientType)
        pasteboard.setData(Data(), forType: concealedType)
        pasteboard.setData(Data(), forType: autoGeneratedType)

        let targetChangeCount = pasteboard.changeCount
        let restoreDelay = holdTimeoutOverride
            ?? calculateRestoreDelay(payloadBytes: text.utf8.count)
        let holdTimeout = holdTimeoutOverride
            ?? max(Self.pasteDeliveryHoldTimeout, restoreDelay)

        DispatchQueue.main.asyncAfter(deadline: .now() + 0.015) { [self] in
            let posted = self.postCmdVKeyEvents()
            if !posted {
                if leaveClipboardOnFailure {
                    // Leave concealed payload for manual ⌘V; restore after the extended hold.
                    DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay) {
                        self.restorePasteboard(
                            pasteboard: pasteboard,
                            oldItems: oldItems,
                            generation: generation,
                            targetChangeCount: targetChangeCount
                        )
                    }
                } else {
                    self.restorePasteboard(
                        pasteboard: pasteboard,
                        oldItems: oldItems,
                        generation: generation,
                        targetChangeCount: targetChangeCount
                    )
                }
                completion(.notPosted)
                return
            }

            guard let expectedText, !expectedText.isEmpty else {
                if completeBeforeRestore {
                    completion(.unavailable)
                    DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay) {
                        self.restorePasteboard(
                            pasteboard: pasteboard,
                            oldItems: oldItems,
                            generation: generation,
                            targetChangeCount: targetChangeCount
                        )
                    }
                } else {
                    DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay) {
                        self.restorePasteboard(
                            pasteboard: pasteboard,
                            oldItems: oldItems,
                            generation: generation,
                            targetChangeCount: targetChangeCount
                        )
                        completion(.unavailable)
                    }
                }
                return
            }

            self.runPasteHoldLoop(
                expectedText: expectedText,
                baseline: baseline,
                pasteAttemptsCompleted: 1,
                holdStarted: Date(),
                holdTimeout: holdTimeout,
                pasteboard: pasteboard,
                oldItems: oldItems,
                generation: generation,
                targetChangeCount: targetChangeCount,
                leaveClipboardOnFailure: leaveClipboardOnFailure,
                completion: completion
            )
        }
    }

    private func runPasteHoldLoop(
        expectedText: String,
        baseline: FocusedTextObservation?,
        pasteAttemptsCompleted: Int,
        holdStarted: Date,
        holdTimeout: TimeInterval,
        pasteboard: NSPasteboard,
        oldItems: [[NSPasteboard.PasteboardType: Data]]?,
        generation: UInt64,
        targetChangeCount: Int,
        leaveClipboardOnFailure: Bool = false,
        completion: @escaping (PasteDeliveryResult) -> Void
    ) {
        DispatchQueue.main.asyncAfter(deadline: .now() + Self.pasteDeliverySettleDelay) { [self] in
            let delivery = verifyFocusedTextDelivery(expectedText: expectedText, baseline: baseline)
            let elapsed = Date().timeIntervalSince(holdStarted)
            let decision = Self.decidePasteHold(
                delivery: delivery,
                pasteAttemptsCompleted: pasteAttemptsCompleted,
                elapsed: elapsed,
                holdTimeout: holdTimeout
            )

            switch decision {
            case .succeed:
                restorePasteboard(
                    pasteboard: pasteboard,
                    oldItems: oldItems,
                    generation: generation,
                    targetChangeCount: targetChangeCount
                )
                completion(.delivered)

            case .failConfirmed:
                DevTypeLog.inject.error(
                    "[Inject] paste hold: AX readable but expected text missing after \(pasteAttemptsCompleted, privacy: .public) Cmd+V attempt(s)"
                )
                if leaveClipboardOnFailure {
                    DispatchQueue.main.asyncAfter(deadline: .now() + holdTimeout) {
                        self.restorePasteboard(
                            pasteboard: pasteboard,
                            oldItems: oldItems,
                            generation: generation,
                            targetChangeCount: targetChangeCount
                        )
                    }
                } else {
                    restorePasteboard(
                        pasteboard: pasteboard,
                        oldItems: oldItems,
                        generation: generation,
                        targetChangeCount: targetChangeCount
                    )
                }
                completion(.failed)

            case .giveUpUnverified:
                restorePasteboard(
                    pasteboard: pasteboard,
                    oldItems: oldItems,
                    generation: generation,
                    targetChangeCount: targetChangeCount
                )
                completion(.unavailable)

            case .retryPaste:
                DevTypeLog.inject.notice(
                    "[Inject] paste hold: retrying Cmd+V (attempt \(pasteAttemptsCompleted + 1, privacy: .public))"
                )
                if postCmdVKeyEvents() {
                    runPasteHoldLoop(
                        expectedText: expectedText,
                        baseline: baseline,
                        pasteAttemptsCompleted: pasteAttemptsCompleted + 1,
                        holdStarted: holdStarted,
                        holdTimeout: holdTimeout,
                        pasteboard: pasteboard,
                        oldItems: oldItems,
                        generation: generation,
                        targetChangeCount: targetChangeCount,
                        leaveClipboardOnFailure: leaveClipboardOnFailure,
                        completion: completion
                    )
                } else {
                    if leaveClipboardOnFailure {
                        DispatchQueue.main.asyncAfter(deadline: .now() + holdTimeout) {
                            self.restorePasteboard(
                                pasteboard: pasteboard,
                                oldItems: oldItems,
                                generation: generation,
                                targetChangeCount: targetChangeCount
                            )
                        }
                    } else {
                        restorePasteboard(
                            pasteboard: pasteboard,
                            oldItems: oldItems,
                            generation: generation,
                            targetChangeCount: targetChangeCount
                        )
                    }
                    completion(.failed)
                }

            case .waitMore:
                runPasteHoldLoop(
                    expectedText: expectedText,
                    baseline: baseline,
                    pasteAttemptsCompleted: pasteAttemptsCompleted,
                    holdStarted: holdStarted,
                    holdTimeout: holdTimeout,
                    pasteboard: pasteboard,
                    oldItems: oldItems,
                    generation: generation,
                    targetChangeCount: targetChangeCount,
                    leaveClipboardOnFailure: leaveClipboardOnFailure,
                    completion: completion
                )
            }
        }
    }

    /// Clipboard-pastes an image (TIFF + PNG reps) with the same snapshot/restore
    /// discipline as `pasteViaClipboard`. Used by image snippets only.
    public func pasteImageViaClipboard(image: NSImage, completion: ((Bool) -> Void)? = nil) {
        guard CGPreflightPostEventAccess() else {
            DevTypeLog.inject.error("[Inject] image paste refused — Post Events denied at paste time")
            completion?(false)
            return
        }

        let pasteboard = NSPasteboard.general

        let oldItems = pasteboard.pasteboardItems?.compactMap { item -> [NSPasteboard.PasteboardType: Data]? in
            var dict = [NSPasteboard.PasteboardType: Data]()
            for type in item.types {
                if let data = item.data(forType: type) {
                    dict[type] = data
                }
            }
            return dict
        }

        let generation = beginRestoreGeneration()

        pasteboard.clearContents()
        var wrote = false
        if let tiff = image.tiffRepresentation {
            pasteboard.setData(tiff, forType: .tiff)
            wrote = true
        }
        if let cgImage = image.cgImage(forProposedRect: nil, context: nil, hints: nil) {
            let rep = NSBitmapImageRep(cgImage: cgImage)
            if let png = rep.representation(using: .png, properties: [:]) {
                pasteboard.setData(png, forType: .png)
                wrote = true
            }
        }
        guard wrote else {
            completion?(false)
            return
        }
        pasteboard.setData(Data(), forType: transientType)
        pasteboard.setData(Data(), forType: concealedType)
        pasteboard.setData(Data(), forType: autoGeneratedType)

        let targetChangeCount = pasteboard.changeCount
        let payloadBytes = (pasteboard.data(forType: .tiff)?.count ?? 0) + (pasteboard.data(forType: .png)?.count ?? 0)
        let restoreDelay = calculateRestoreDelay(payloadBytes: payloadBytes)

        DispatchQueue.main.asyncAfter(deadline: .now() + 0.015) { [self] in
            let posted = self.postCmdVKeyEvents()
            if !posted {
                self.restorePasteboard(
                    pasteboard: pasteboard,
                    oldItems: oldItems,
                    generation: generation,
                    targetChangeCount: targetChangeCount
                )
                completion?(false)
                return
            }

            DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay) {
                defer { completion?(true) }
                self.restorePasteboard(
                    pasteboard: pasteboard,
                    oldItems: oldItems,
                    generation: generation,
                    targetChangeCount: targetChangeCount
                )
            }
        }
    }

    private func restorePasteboard(
        pasteboard: NSPasteboard,
        oldItems: [[NSPasteboard.PasteboardType: Data]]?,
        generation: UInt64,
        targetChangeCount: Int
    ) {
        // Generation gate: a newer expand owns the pasteboard — skip stale restore.
        guard currentRestoreGeneration() == generation else { return }
        guard pasteboard.changeCount == targetChangeCount else { return }

        pasteboard.clearContents()
        guard let oldItems, !oldItems.isEmpty else { return }

        let restoredItems: [NSPasteboardItem] = oldItems.map { itemDict in
            let newItem = NSPasteboardItem()
            itemDict.forEach { type, data in
                newItem.setData(data, forType: type)
            }
            return newItem
        }
        pasteboard.writeObjects(restoredItems)
    }

    @discardableResult
    public func beginRestoreGeneration() -> UInt64 {
        restoreLock.lock()
        restoreGeneration = Self.nextRestoreGeneration(current: restoreGeneration)
        let token = restoreGeneration
        restoreLock.unlock()
        return token
    }

    public func currentRestoreGeneration() -> UInt64 {
        restoreLock.lock()
        defer { restoreLock.unlock() }
        return restoreGeneration
    }

    @discardableResult
    /// Physical ⌘V: Command down → V → Command up (15 ms gaps). Flag-only ⌘V fails under many IMEs.
    /// Used only on the HID clipboard paste path — never on AX range replace.
    public func postCmdVKeyEvents() -> Bool {
        // Re-check at post time — CGEvent create-success is not delivery proof if Post was revoked.
        guard CGPreflightPostEventAccess() else {
            DevTypeLog.inject.error(
                "[Inject] Cmd+V refused — CGPreflightPostEventAccess false at post time"
            )
            return false
        }

        let source = makeTaggedEventSource()
        let command = CGKeyCode(kVK_Command)
        let vKeyCode = resolveVirtualKeyCodeForChar("v") ?? CGKeyCode(kVK_ANSI_V)

        if let cmdDown = CGEvent(keyboardEventSource: source, virtualKey: command, keyDown: true) {
            cmdDown.flags = .maskCommand
            cmdDown.post(tap: .cghidEventTap)
        }
        usleep(15_000)

        guard let vDown = CGEvent(keyboardEventSource: source, virtualKey: vKeyCode, keyDown: true),
              let vUp = CGEvent(keyboardEventSource: source, virtualKey: vKeyCode, keyDown: false) else {
            DevTypeLog.inject.error(
                "[Inject] Cmd+V CGEvent create failed — Post Events may be revoked or CG HID unavailable"
            )
            return false
        }
        vDown.flags = .maskCommand
        vUp.flags = .maskCommand
        vDown.post(tap: .cghidEventTap)
        vUp.post(tap: .cghidEventTap)
        usleep(15_000)

        if let cmdUp = CGEvent(keyboardEventSource: source, virtualKey: command, keyDown: false) {
            cmdUp.flags = []
            cmdUp.post(tap: .cghidEventTap)
        }
        return true
    }

    private func resolveVirtualKeyCodeForChar(_ targetChar: Character) -> CGKeyCode? {
        guard let inputSource = TISCopyCurrentKeyboardInputSource()?.takeRetainedValue(),
              let layoutData = TISGetInputSourceProperty(inputSource, kTISPropertyUnicodeKeyLayoutData) else {
            return 9
        }

        let data = unsafeBitCast(layoutData, to: CFData.self)
        guard let bytes = CFDataGetBytePtr(data) else { return 9 }

        return bytes.withMemoryRebound(to: UCKeyboardLayout.self, capacity: 1) { keyboardLayout -> CGKeyCode in
            var chars = [UniChar](repeating: 0, count: 4)
            var realLength = 0

            for code: CGKeyCode in 0..<128 {
                var deadKeyState: UInt32 = 0
                let status = UCKeyTranslate(
                    keyboardLayout,
                    code,
                    UInt16(kUCKeyActionDisplay),
                    0,
                    UInt32(KBGetLayoutType(0)),
                    OptionBits(kUCKeyTranslateNoDeadKeysBit),
                    &deadKeyState,
                    4,
                    &realLength,
                    &chars
                )
                if status == noErr && realLength > 0 {
                    let str = String(utf16CodeUnits: chars, count: realLength)
                    if str.lowercased() == String(targetChar).lowercased() {
                        return code
                    }
                }
            }
            return 9
        }
    }

    public func captureFocusedTextObservation() -> FocusedTextObservation? {
        guard let axElement = AXContextChecker.shared.focusedElement() else { return nil }
        return focusedTextObservation(for: axElement)
    }

    public func verifyFocusedTextDelivery(
        expectedText: String,
        baseline: FocusedTextObservation?
    ) -> TextDeliveryVerification {
        Self.verifyTextDelivery(
            expectedText: expectedText,
            baseline: baseline,
            after: captureFocusedTextObservation()
        )
    }

    public static func verifyTextDelivery(
        expectedText: String,
        baseline: FocusedTextObservation?,
        after: FocusedTextObservation?
    ) -> TextDeliveryVerification {
        guard !expectedText.isEmpty else { return .delivered }
        guard let after else { return .unavailable }
        if after.selectedText == expectedText {
            return .delivered
        }
        guard let value = after.value else {
            return .unavailable
        }
        guard value.contains(expectedText) else {
            return .failed
        }
        guard let baseline else {
            return .delivered
        }
        let baselineContainsExpected = baseline.value?.contains(expectedText) == true
        if value != baseline.value || after.selectedText != baseline.selectedText || !baselineContainsExpected {
            return .delivered
        }
        return .unavailable
    }

    private func focusedTextObservation(for axElement: AXUIElement) -> FocusedTextObservation {
        var value: String?
        var selectedText: String?

        var valueRef: CFTypeRef?
        if AXUIElementCopyAttributeValue(axElement, kAXValueAttribute as CFString, &valueRef) == .success {
            value = valueRef as? String
        }

        var selectedTextRef: CFTypeRef?
        if AXUIElementCopyAttributeValue(axElement, kAXSelectedTextAttribute as CFString, &selectedTextRef) == .success {
            selectedText = selectedTextRef as? String
        }

        return FocusedTextObservation(value: value, selectedText: selectedText)
    }

    public func sendBackspaces(count: Int) {
        guard count > 0 else { return }
        guard CGPreflightPostEventAccess() else {
            DevTypeLog.inject.error(
                "[Inject] backspace refused — CGPreflightPostEventAccess false at post time count=\(count, privacy: .public)"
            )
            return
        }
        let source = makeTaggedEventSource()
        var posted = 0
        for _ in 0..<count {
            if let bDown = CGEvent(keyboardEventSource: source, virtualKey: 51, keyDown: true),
               let bUp = CGEvent(keyboardEventSource: source, virtualKey: 51, keyDown: false) {
                bDown.post(tap: .cghidEventTap)
                bUp.post(tap: .cghidEventTap)
                posted += 1
            }
        }
        if posted == 0 {
            DevTypeLog.inject.error(
                "[Inject] backspace CGEvent create failed count=\(count, privacy: .public) — Post Events may be revoked"
            )
        } else if posted < count {
            DevTypeLog.inject.notice(
                "[Inject] backspace CGEvent partial posted=\(posted, privacy: .public)/\(count, privacy: .public)"
            )
        }
    }

    private func sendBackspacesAsync(count: Int, completion: @escaping () -> Void) {
        guard count > 0 else {
            completion()
            return
        }
        sendBackspaces(count: count)
        DispatchQueue.main.asyncAfter(deadline: .now() + Double(count) * 0.002 + 0.01, execute: completion)
    }

    /// Collapses any non-empty selection to the caret at its trailing edge.
    ///
    /// A selection sitting in the field when we are about to post backspaces is almost always our
    /// own leftover (an AX replace that widened the range then failed). Backspace #1 would consume
    /// the whole selection and every subsequent backspace would eat the user's preceding text — the
    /// "expansion deleted the previous N characters" bug. Collapsing to the trailing edge makes the
    /// backspace count mean exactly what it says.
    @discardableResult
    public func collapseSelectionToCaret(element: AXUIElement? = nil) -> Bool {
        guard let axElement = element ?? AXContextChecker.shared.focusedElement() else { return false }

        var rangeRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(axElement, kAXSelectedTextRangeAttribute as CFString, &rangeRef) == .success,
              let rangeValue = rangeRef,
              CFGetTypeID(rangeValue) == AXValueGetTypeID() else {
            return false
        }
        var range = CFRange(location: 0, length: 0)
        guard AXValueGetValue(unsafeBitCast(rangeValue, to: AXValue.self), .cfRange, &range) else {
            return false
        }
        guard range.length > 0 else { return true }

        DevTypeLog.inject.notice(
            "[Inject] collapsing stray selection before erase length=\(range.length, privacy: .public)"
        )
        // Trailing edge, deliberately. The selection we are cleaning up was produced by a failed AX
        // replace, which widens *backwards* from the caret to cover the trigger — so the trailing
        // edge is where the caret was before we touched it, and `backspaceCount` backspaces from
        // there remove exactly the trigger.
        var caret = CFRange(location: range.location + range.length, length: 0)
        guard let caretValue = AXValueCreate(.cfRange, &caret) else { return false }
        return AXUIElementSetAttributeValue(
            axElement,
            kAXSelectedTextRangeAttribute as CFString,
            caretValue
        ) == .success
    }

    /// Collapse stray selection → re-verify the erase precondition → post backspaces.
    ///
    /// The precondition is checked again here (not only at the top of `injectOnMain`) because
    /// everything between the two checks — an AX replace attempt, a macro resolve, a fill-in panel —
    /// can move the caret or change the field. This is the last gate before text is destroyed.
    /// `completion(false)` means the erase was refused and the caller must abort the expand.
    private func performGuardedErase(plan: ErasePlan, completion: @escaping (Bool) -> Void) {
        guard plan.backspaceCount > 0 else {
            completion(true)
            return
        }
        // Resolve focus once and share it: `AXContextChecker.focusedElement()` is a multi-step AX
        // round trip and this sits on the keystroke path. Attribute reads through the handle stay
        // live, so the precondition still sees the post-collapse selection.
        let element = AXContextChecker.shared.focusedElement()
        collapseSelectionToCaret(element: element)
        if case .mismatch(let why) = evaluateErasePrecondition(plan: plan, element: element) {
            DevTypeLog.inject.error(
                "[Inject] erase aborted before backspaces — \(why, privacy: .public)"
            )
            // #region agent log
            Self.debugLogInject(
                hypothesisId: "M5",
                message: "guarded erase aborted",
                data: ["why": why, "eraseBackspaces": plan.backspaceCount]
            )
            // #endregion
            completion(false)
            return
        }
        sendBackspacesAsync(count: plan.backspaceCount) { completion(true) }
    }

