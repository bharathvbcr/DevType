    /// §8.2: the collapsed form. Identical semantics; `swallowed` replaces four parameters.
    public func inject(
        snippet: SnippetModel,
        triggerLength: Int,
        swallowed: SwallowedKey,
        clipboardOverride: String? = nil,
        lastEventCharacterCount: Int = 1,
        plan: InjectionPlan? = nil,
