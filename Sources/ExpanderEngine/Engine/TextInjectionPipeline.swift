/// §8.2: the four values that describe "the key the event tap ate on our behalf".
///
/// `swallowedFinalKey` / `swallowedUnicode` / `swallowedKeyCode` / `swallowedFlags` used to travel
/// as four separate parameters through nine signatures — `inject`, `injectOnMain`,
/// `injectSecureClipboardPasteOnMain`, `refuseInjectKeepingSwallow`, `finishPasteDelivery`,
/// `restoreTriggerAfterFailedPaste`, and their mirrors in `EventTapEngine`. Thirty-six parameters
/// carrying nine pieces of information.
///
/// This also folds in `EventTapEngine.mustReinjectOnRefuse(didSwallow:)`, which is the single rule
/// that makes the swallow contract safe: the tap only returns `nil` for the trigger key after the
/// planner has synchronously said the expand may proceed, so a later refuse owes the user
/// that keystroke back while the target is unchanged. A changed erase context suppresses replay.
public struct SwallowedKey {
    /// True when the event tap swallowed the final trigger key (`return nil` from the callback).
    public let didSwallow: Bool
    public let unicode: String
    public let keyCode: Int64
    public let flags: CGEventFlags

    public init(
        didSwallow: Bool,
        unicode: String = "",
        keyCode: Int64 = 0,
        flags: CGEventFlags = []
    ) {
        self.didSwallow = didSwallow
        self.unicode = unicode
        self.keyCode = keyCode
        self.flags = flags
    }

    /// Nothing was swallowed — explicit inject paths (hotkey, inline search, Test Expansion Lab).
    public static let notSwallowed = SwallowedKey(didSwallow: false)

    /// §8.2: `EventTapEngine.mustReinjectOnRefuse(didSwallow:)` is delegated to rather than
    /// duplicated, so the swallow contract keeps exactly one definition.
    public var mustReinjectOnRefuse: Bool {
        EventTapEngine.mustReinjectOnRefuse(didSwallow: didSwallow)
    }

    /// False when there is nothing to post back (no character and no key code).
    public var hasPayload: Bool {
        !unicode.isEmpty || keyCode != 0
    }
}

/// The policy coordinator for text injection.
///
/// §8.1: the mechanics live in five collaborators this type owns — `HIDKeyPoster` (every CGEvent),
/// `PasteboardBroker` (the clipboard snapshot/restore invariant), `AXTextWriter` (the only code
/// touching `kAXSelectedText*`), `DeliveryVerifier` (did it land?) and `EraseExecutor` (what gets
/// deleted, and proving that is safe). What is left here is the decision-making: which path to
/// take, when to refuse, and what to tell the user afterwards.
///
/// The safety contract, unchanged:
/// * fail closed when AX is unavailable,
/// * refuse inside secure text fields, during IME composition, and in muted apps,
/// * the trigger key is swallowed only after a sync-safe planner allow; an asynchronous refuse
///   reinjects it unless input/focus changes made replay unsafe.
public final class TextInjectionPipeline {
    public static let shared = TextInjectionPipeline()

    /// Terminal result delivered to an inject caller after the pipeline has restored or retained
    /// the pasteboard. Callers must use this result for side effects; completion is not a synonym
    /// for success because refusals and delivery failures also need to release their state.
    public typealias InjectionCompletion = (PermissionCoordinator.InjectOutcome) -> Void

